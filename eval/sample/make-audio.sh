#!/bin/sh
# 評価の手順を試すためのサンプル音声を macOS の読み上げ（say）で作る。
# 本番の評価には、実際の登壇の録音を使うこと（読み上げ音声は人の発話より認識しやすい）。
set -eu
cd "$(dirname "$0")"
mkdir -p ../data
say -v Kyoko -o ../data/smoke.aiff "今日はデュラブルオブジェクトを使ってリアルタイム字幕を作った話をします。 [[slnc 1200]] 部屋ごとに一つ用意してウェブソケットをつないでいます。 [[slnc 1200]] 参加者の接続はハイバネーションできるので、待機中のコストがほとんどかかりません。"
echo "../data/smoke.aiff を作りました"
